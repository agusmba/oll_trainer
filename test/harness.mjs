// Headless harness for the OLL Trainer app.
// Launches chromium-headless-shell, loads the app at `url` (the local index.html
// file by default; an http:// origin when the caller supplies one), collects
// everything the app complains about, then hands back a page. Keep assertions in
// JS, not in the model: tests print a few lines, not the whole page.

import { chromium } from 'playwright';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import { serveRepo } from './server.mjs';

const APP_URL = pathToFileURL(path.resolve(process.cwd(), 'index.html')).href;

/// \returns { page, browser, errors, failedRequests, close }
export async function openApp({ url = APP_URL } = {}) {
    const browser = await chromium.launch();
    const page = await browser.newPage();

    const errors = [];
    page.on('pageerror', e => errors.push(`pageerror: ${e.message}`));
    page.on('console', m => { if (m.type() === 'error') errors.push(`console.error: ${m.text()}`); });

    const failedRequests = [];
    page.on('requestfailed', r => failedRequests.push(`${r.url()} -> ${r.failure?.errorText}`));

    await page.goto(url);
    await page.waitForTimeout(100); // let the inline changeMode("selection") render settle

    return {
        page,
        browser,
        errors,
        failedRequests,
        close: () => browser.close(),
    };
}

/// The app served over http:// under a Pages-style subpath (raw files, nothing
/// processed). \returns what openApp returns, plus `server` and a close that shuts both.
export async function openServedApp({ prefix = '/oll/' } = {}) {
    const server = await serveRepo({ prefix });
    const app = await openApp({ url: server.url });
    return {
        ...app,
        server,
        close: async () => { await app.close(); await server.close(); },
    };
}

/// \returns array of selected case numbers
export function selectedCases(page) {
    return page.evaluate(() => window.selCases.slice());
}

/// \returns the case number last generated by generateScramble()
export function lastCase(page) {
    return page.evaluate(() => window.lastCase);
}

/// \returns true when a scramble string only uses WCA face/rotation moves
export async function isValidScramble(page) {
    const text = await page.evaluate(() => document.getElementById('scramble').textContent);
    const moves = text.replace(/^scramble:\s*/, '').split(/\s+/).filter(Boolean);
    const legal = /^(R|L|U|D|F|B|y|y2|y')(2|')?$/;
    return { moves, ok: moves.length > 0 && moves.every(m => legal.test(m)) };
}

/// \returns rendered case cell ids, e.g. ["itemTd1", ...]
export function caseCellIds(page) {
    return page.evaluate(() =>
        [...document.querySelectorAll('#cases_selection td[id^="itemTd"]')].map(td => td.id));
}

/// Clicks the case picture for case number i.
export async function clickCase(page, i) {
    await page.click(`#itemTd${i}`);
}

/// Clicks the group header (e.g. "P-Shapes") to toggle a whole group.
export async function clickGroup(page, groupName) {
    await page.click(`#cases_selection td:has(b:text-is("${groupName}"))`);
}

/// Clicks Practice (Practice Mode) or Recap (Recap Mode).
export async function clickPractice(page) { await page.click('#practiceButton'); }
export async function clickRecap(page) { await page.click('#recapButton'); }

/// \returns href of the sidebar anchor whose visible text is `label`, or null if absent.
export function sidebarHref(page, label) {
    return page.evaluate(text => {
        const link = [...document.querySelectorAll('.selection_layout a')].find(a => a.textContent.trim() === text);
        return link ? link.href : null;
    }, label);
}
